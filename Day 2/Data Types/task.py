# Subscripting
print("Hello"[0])

name = "Manav"
print(name[-1])   # v  (last character)
print(name[-2])   # a  (second to last)

# Slicing is also a form of subscripting:
name = "Manav"
print(name[0:3])  # Man  (from index 0 up to, but not including, 3)
print(name[1:])   # anav (from index 1 to the end)
print(name[::-1]) # vanaM (whole string reversed)

#String concatenation
print("123" + "456")

# Integer = Whole Number
print(123 + 456)

# Large Integers
print(123_456_789)

# Float = Floating Point Number
print(3.14259)

# Boolean
print(True)
print(False)



