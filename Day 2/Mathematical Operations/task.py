# Converts the number 12 to the string "12" using str(), then joins it to the label with +
# Without str(), this would raise a TypeError (string + int)
print("My age: " + str(12))

# Addition: adds the two integers and prints 579
print(123 + 456)

# Subtraction: subtracts 3 from 7 and prints 4
print(7 - 3)

# Multiplication: multiplies 3 by 2 and prints 6
print(3 * 2)

# Division: always returns a float in Python 3, so this prints 2.0 (not 2)
print(6 / 3)
print(type(6 / 3))

# Floor division: divides and rounds down to a whole number, so this prints 2 (an int)
print(6 // 3)
print(type(6 //3))


